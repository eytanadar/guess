// Writes py/guess/_colorscales.py: the colour scales of d3-scale-chromatic
// (ColorBrewer, viridis and friends, turbo, rainbow, ...) and the extra
// schemes of Vega, sampled from the copies in web/node_modules.
//
//     node py/tools/gen_colorscales.mjs
//
// Continuous scales are sampled at 33 evenly spaced points (GUESS interpolates
// between them); categorical schemes and ColorBrewer's discrete schemes (3 to
// 9 or 11 classes) are copied as they are.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const nm = resolve(here, "../../web/node_modules");
const d3 = await import(pathToFileURL(`${nm}/d3-scale-chromatic/dist/d3-scale-chromatic.mjs`).href);
const vega = await import(pathToFileURL(`${nm}/vega-scale/build/vega-scale.js`).href).catch(
  () => import(pathToFileURL(`${nm}/vega-scale/build/vega-scale.module.js`).href));
// "#abc", "#aabbcc" or "rgb(r, g, b)" -> "#aabbcc"
function hex(c) {
  if (/^#[0-9a-f]{6}$/i.test(c)) return c.toLowerCase();
  if (/^#[0-9a-f]{3}$/i.test(c)) return "#" + [...c.slice(1)].map((x) => x + x).join("").toLowerCase();
  const m = /^rgba?\(([^)]+)\)$/.exec(c);
  if (!m) throw new Error(`not a colour: ${c}`);
  return "#" + m[1].split(",").slice(0, 3).map((v) => Math.max(0, Math.min(255, Math.round(+v))).toString(16).padStart(2, "0")).join("");
}
const SAMPLES = 33;
const sample = (f) => Array.from({ length: SAMPLES }, (_, i) => hex(f(i / (SAMPLES - 1))));

// [name, kind, d3 interpolator name]
const D3 = [
  ...["Blues", "Greens", "Greys", "Oranges", "Purples", "Reds",
    "BuGn", "BuPu", "GnBu", "OrRd", "PuBuGn", "PuBu", "PuRd", "RdPu", "YlGnBu", "YlGn", "YlOrBr", "YlOrRd"]
    .map((n) => [n, "sequential", n]),
  ...[["viridis", "Viridis"], ["inferno", "Inferno"], ["magma", "Magma"], ["plasma", "Plasma"],
    ["cividis", "Cividis"], ["turbo", "Turbo"], ["warm", "Warm"], ["cool", "Cool"], ["cubehelix", "CubehelixDefault"]]
    .map(([n, f]) => [n, "sequential", f]),
  ...["BrBG", "PRGn", "PiYG", "PuOr", "RdBu", "RdGy", "RdYlBu", "RdYlGn", "Spectral"].map((n) => [n, "diverging", n]),
  ["rainbow", "cyclical", "Rainbow"], ["sinebow", "cyclical", "Sinebow"],
];
const D3_CATEGORICAL = ["Category10", "Tableau10", "Observable10", "Accent", "Dark2", "Paired",
  "Pastel1", "Pastel2", "Set1", "Set2", "Set3"];
const VEGA_SEQ = ["tealblues", "teals", "browns", "warmgreys", "goldgreen", "goldorange", "goldred",
  "lightgreyred", "lightgreyteal", "lightmulti", "lightorange", "lighttealblue",
  "darkblue", "darkgold", "darkgreen", "darkmulti", "darkred"];
const VEGA_DIV = ["blueorange"];
const VEGA_CAT = ["category20", "category20b", "category20c", "tableau20"];

const scales = [];
for (const [name, kind, f] of D3) scales.push([name, kind, "d3", sample(d3[`interpolate${f}`])]);
for (const n of VEGA_SEQ) scales.push([n, "sequential", "vega", sample(vega.scheme(n))]);
for (const n of VEGA_DIV) scales.push([n, "diverging", "vega", sample(vega.scheme(n))]);
for (const n of D3_CATEGORICAL) {
  const name = n.startsWith("Category") || n.startsWith("Tableau") || n.startsWith("Observable") ? n.toLowerCase() : n;
  scales.push([name, "categorical", "d3", d3[`scheme${n}`].map(hex)]);
}
for (const n of VEGA_CAT) scales.push([n, "categorical", "vega", vega.scheme(n).map(hex)]);

// ColorBrewer's own discrete schemes, by number of classes
const discrete = {};
for (const [name, kind] of D3) {
  const s = d3[`scheme${name}`];
  if (kind === "cyclical" || !Array.isArray(s)) continue;
  discrete[name] = {};
  s.forEach((cols, k) => { if (cols) discrete[name][k] = cols.map(hex); });
}

const py = [
  '"""Colour scales, generated by py/tools/gen_colorscales.mjs from',
  "d3-scale-chromatic (ISC licence; ColorBrewer schemes by Cynthia Brewer,",
  "Apache licence; viridis, magma, inferno and plasma by Stéfan van der Walt",
  "and Nathaniel Smith, CC0; cividis by Jamie Nuñez et al.; turbo by Anton",
  'Mikhailov, Apache licence) and Vega\'s extra schemes (BSD licence). Do not edit."""',
  "",
  "# name -> (kind, source, colours: continuous scales sampled evenly, categorical in order)",
  "SCALES = {",
  ...scales.map(([n, k, src, cols]) => `    ${JSON.stringify(n)}: (${JSON.stringify(k)}, ${JSON.stringify(src)}, ${JSON.stringify(cols.join(" "))}),`),
  "}",
  "",
  "# ColorBrewer's discrete schemes: name -> {number of classes: colours}",
  "DISCRETE = {",
  ...Object.entries(discrete).map(([n, ks]) =>
    `    ${JSON.stringify(n)}: {${Object.entries(ks).map(([k, c]) => `${k}: ${JSON.stringify(c.join(" "))}`).join(", ")}},`),
  "}",
  "",
];
const out = resolve(here, "../guess/_colorscales.py");
writeFileSync(out, py.join("\n"));
console.log(`wrote ${out}: ${scales.length} scales, ${Object.keys(discrete).length} with discrete classes`);
